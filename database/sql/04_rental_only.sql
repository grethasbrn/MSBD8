BEGIN;

-- 1. Tambahkan komponen biaya sewa
ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS rentals_total NUMERIC(14,2)
    NOT NULL DEFAULT 0;

-- 2. Paket dan informasi acara boleh kosong untuk transaksi sewa saja
ALTER TABLE orders
    ALTER COLUMN package_id DROP NOT NULL,
    ALTER COLUMN event_date DROP NOT NULL,
    ALTER COLUMN event_location DROP NOT NULL;

-- 3. Paket tidak dipilih berarti harga paket nol
ALTER TABLE orders
    ALTER COLUMN package_price SET DEFAULT 0;

-- 4. Perbarui perhitungan total pesanan
ALTER TABLE orders
    DROP CONSTRAINT IF EXISTS chk_orders_total;

ALTER TABLE orders
    ADD CONSTRAINT chk_orders_total
    CHECK (
        total_amount = package_price + addons_total + rentals_total
    );

-- 5. Tambahkan informasi stok dan harga sewa inventaris
ALTER TABLE inventory_items
    ADD COLUMN IF NOT EXISTS stock_quantity INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS rental_price NUMERIC(14,2) NOT NULL DEFAULT 0;

ALTER TABLE inventory_items
    ADD CONSTRAINT chk_inventory_stock
    CHECK (stock_quantity >= 0);

ALTER TABLE inventory_items
    ADD CONSTRAINT chk_inventory_rental_price
    CHECK (rental_price >= 0);

-- 6. Tabel detail barang yang disewa dalam pesanan
CREATE TABLE IF NOT EXISTS order_rentals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL
        REFERENCES orders(id) ON DELETE CASCADE,

    inventory_item_id BIGINT NOT NULL
        REFERENCES inventory_items(id),

    rental_start_date DATE NOT NULL,
    rental_end_date DATE NOT NULL,

    quantity INTEGER NOT NULL CHECK (quantity > 0),

    rental_price NUMERIC(14,2) NOT NULL CHECK (rental_price >= 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_order_rentals_dates
        CHECK (rental_end_date >= rental_start_date),

    CONSTRAINT chk_order_rentals_subtotal
        CHECK (subtotal = quantity * rental_price)
);

COMMIT;