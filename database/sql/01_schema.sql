-- ---------- Tipe ENUM ----------
CREATE TYPE user_role AS ENUM (
  'customer','owner','korlap','helper','penari','pemusik'
);

CREATE TYPE order_status AS ENUM (
  'pending_verification','approved','cancelled','completed'
);

CREATE TYPE payment_type AS ENUM ('dp','pelunasan');
CREATE TYPE payment_method AS ENUM ('transfer','qris','ewallet','tunai');
CREATE TYPE payment_status AS ENUM ('pending','verified','rejected');
CREATE TYPE package_category AS ENUM ('tari','musik');
CREATE TYPE item_category AS ENUM ('kostum','aksesoris','alat_musik');
CREATE TYPE item_status AS ENUM ('tersedia','dipinjam','rusak','hilang');
CREATE TYPE return_condition AS ENUM ('baik','rusak','hilang');
CREATE TYPE assignment_role AS ENUM ('korlap','penari','pemusik','helper');
CREATE TYPE assignment_status AS ENUM ('ditawarkan','diterima','ditolak','dibatalkan');

-- ---------- Pembuat ID Transaksi ----------
CREATE SEQUENCE order_code_seq START 1;

CREATE FUNCTION fn_generate_order_code() RETURNS varchar
LANGUAGE sql AS $$
  SELECT 'SNG-' || to_char(now() AT TIME ZONE 'Asia/Jakarta', 'YYMMDD')
         || '-' || lpad(nextval('order_code_seq')::text, 4, '0')
$$;

-- ---------- Pengguna ----------
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  password VARCHAR(255) NOT NULL,
  role user_role NOT NULL DEFAULT 'customer',
  specialization VARCHAR(100),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  remember_token VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_uq ON users (lower(email));
CREATE UNIQUE INDEX users_phone_uq ON users (phone);
CREATE INDEX users_role_idx ON users (role) WHERE is_active;

-- ---------- Paket ----------
CREATE TABLE packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  category package_category NOT NULL,
  description TEXT,
  price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
  dancers_needed SMALLINT NOT NULL DEFAULT 0 CHECK (dancers_needed >= 0),
  musicians_needed SMALLINT NOT NULL DEFAULT 0 CHECK (musicians_needed >= 0),
  helpers_needed SMALLINT NOT NULL DEFAULT 1 CHECK (helpers_needed >= 0),
  image_url TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Add-on ----------
CREATE TABLE addons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  description TEXT,
  price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
  extra_dancers SMALLINT NOT NULL DEFAULT 0 CHECK (extra_dancers >= 0),
  extra_musicians SMALLINT NOT NULL DEFAULT 0 CHECK (extra_musicians >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Inventaris dan katalog penyewaan ----------
CREATE TABLE inventory_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  category item_category NOT NULL,
  status item_status NOT NULL DEFAULT 'tersedia',
  description TEXT,
  image_url TEXT,
  subcategory VARCHAR(100),
  unit_label VARCHAR(20) NOT NULL DEFAULT 'Unit',

  -- Stok dan harga sewa per unit per hari
  stock_quantity INTEGER NOT NULL DEFAULT 1
    CHECK (stock_quantity >= 0),
  rental_price NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (rental_price >= 0),

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX inventory_items_category_idx
  ON inventory_items (category, status);

-- ---------- Galeri ----------
CREATE TABLE gallery_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  description TEXT,
  media_url TEXT NOT NULL,
  event_date DATE,
  is_published BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Pengaturan ----------
CREATE TABLE app_settings (
  key VARCHAR(60) PRIMARY KEY,
  value TEXT NOT NULL,
  description TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Tarif honor ----------
CREATE TABLE honor_rates (
  role assignment_role PRIMARY KEY,
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Pesanan ----------
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE DEFAULT fn_generate_order_code(),

  customer_id BIGINT NOT NULL REFERENCES users(id),

  -- NULL jika pesanan hanya penyewaan
  package_id BIGINT REFERENCES packages(id),

  -- NULL jika pesanan hanya penyewaan
  event_date DATE,
  event_time TIME,
  event_location TEXT,

  notes TEXT,
  status order_status NOT NULL DEFAULT 'pending_verification',

  package_price NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (package_price >= 0),

  addons_total NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (addons_total >= 0),

  -- Total biaya penyewaan
  rentals_total NUMERIC(14,2) NOT NULL DEFAULT 0
    CHECK (rentals_total >= 0),

  total_amount NUMERIC(14,2) NOT NULL,
  min_dp_amount NUMERIC(14,2) NOT NULL,

  compensation_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
  cancel_reason TEXT,
  cancelled_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  field_report TEXT,
  lunas_at TIMESTAMPTZ,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_orders_total
    CHECK (
      total_amount = package_price + addons_total + rentals_total
    ),

  CONSTRAINT chk_orders_dp
    CHECK (min_dp_amount >= 0 AND min_dp_amount <= total_amount),

  -- Pesanan harus berupa pertunjukan, penyewaan, atau keduanya
  CONSTRAINT chk_orders_type
    CHECK (
      package_id IS NOT NULL
      OR rentals_total > 0
    ),

  -- Pesanan pertunjukan wajib memiliki tanggal dan lokasi acara
  CONSTRAINT chk_orders_event_data
    CHECK (
      package_id IS NULL
      OR (event_date IS NOT NULL AND event_location IS NOT NULL)
    )
);

CREATE INDEX orders_event_date_idx ON orders (event_date);
CREATE INDEX orders_status_idx ON orders (status);
CREATE INDEX orders_customer_idx ON orders (customer_id);

-- ---------- Detail add-on pesanan ----------
CREATE TABLE order_addons (
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  addon_id BIGINT NOT NULL REFERENCES addons(id),
  price_at_order NUMERIC(14,2) NOT NULL CHECK (price_at_order >= 0),
  PRIMARY KEY (order_id, addon_id)
);

-- ---------- Detail barang yang disewa ----------
CREATE TABLE order_rentals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  order_id BIGINT NOT NULL
    REFERENCES orders(id) ON DELETE CASCADE,

  item_id BIGINT NOT NULL
    REFERENCES inventory_items(id),

  quantity INTEGER NOT NULL CHECK (quantity > 0),

  -- Snapshot agar harga lama tidak berubah
  -- saat Owner mengubah harga katalog
  item_name_snapshot VARCHAR(150) NOT NULL,
  price_at_order NUMERIC(14,2) NOT NULL
    CHECK (price_at_order >= 0),

  start_date DATE NOT NULL,
  end_date DATE NOT NULL,

  subtotal NUMERIC(14,2) NOT NULL
    CHECK (subtotal >= 0),

  CONSTRAINT chk_rental_dates
    CHECK (end_date >= start_date),

  CONSTRAINT uq_order_rental_item
    UNIQUE (order_id, item_id)
);

CREATE INDEX order_rentals_dates_idx
  ON order_rentals (item_id, start_date, end_date);

CREATE INDEX order_rentals_order_idx
  ON order_rentals (order_id);

-- ---------- Log perubahan status pesanan ----------
CREATE TABLE order_status_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  from_status order_status,
  to_status order_status NOT NULL,
  changed_by BIGINT REFERENCES users(id),
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX order_status_logs_order_idx
  ON order_status_logs (order_id);

-- ---------- Kuota harian pertunjukan ----------
CREATE TABLE daily_quota (
  event_date DATE PRIMARY KEY,
  booked_slots INTEGER NOT NULL DEFAULT 0
    CHECK (booked_slots >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Pembayaran ----------
CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  type payment_type NOT NULL,
  method payment_method NOT NULL DEFAULT 'transfer',
  amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  proof_path TEXT,
  received_by BIGINT REFERENCES users(id),
  status payment_status NOT NULL DEFAULT 'pending',
  reject_reason TEXT,
  verified_by BIGINT REFERENCES users(id),
  verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_payments_proof
    CHECK (method = 'tunai' OR proof_path IS NOT NULL),

  CONSTRAINT chk_payments_verified
    CHECK (
      status <> 'verified'
      OR (verified_by IS NOT NULL AND verified_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX payments_one_pending_uq
  ON payments (order_id, type)
  WHERE status = 'pending';

CREATE UNIQUE INDEX payments_one_verified_uq
  ON payments (order_id, type)
  WHERE status = 'verified';

CREATE INDEX payments_status_idx ON payments (status);

-- ---------- Penugasan tim ----------
CREATE TABLE event_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  role assignment_role NOT NULL,
  instrument VARCHAR(100),
  event_date DATE NOT NULL,
  status assignment_status NOT NULL DEFAULT 'ditawarkan',
  assigned_by BIGINT REFERENCES users(id),
  responded_at TIMESTAMPTZ,
  attended_at TIMESTAMPTZ,
  attendance_by BIGINT REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_assign_attend
    CHECK (attended_at IS NULL OR status = 'diterima')
);

CREATE UNIQUE INDEX ea_one_korlap_uq
  ON event_assignments (order_id)
  WHERE role = 'korlap'
    AND status IN ('ditawarkan','diterima');

CREATE UNIQUE INDEX ea_no_double_booking_uq
  ON event_assignments (user_id, event_date)
  WHERE status IN ('ditawarkan','diterima');

CREATE INDEX ea_order_idx ON event_assignments (order_id);

-- ---------- Honorarium ----------
CREATE TABLE honorariums (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL UNIQUE REFERENCES event_assignments(id),
  amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
  paid_by BIGINT NOT NULL REFERENCES users(id),
  paid_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Peminjaman fisik barang ----------
-- Tetap digunakan untuk mencatat barang yang benar-benar keluar
-- dan dikembalikan, bukan untuk reservasi tanggal penyewaan.
CREATE TABLE item_loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id BIGINT NOT NULL REFERENCES inventory_items(id),
  order_id BIGINT NOT NULL REFERENCES orders(id),
  borrowed_by BIGINT NOT NULL REFERENCES users(id),
  borrowed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  returned_at TIMESTAMPTZ,
  returned_by BIGINT REFERENCES users(id),
  return_condition return_condition,
  notes TEXT,

  CONSTRAINT chk_loans_return
    CHECK (
      returned_at IS NULL
      OR (return_condition IS NOT NULL AND returned_by IS NOT NULL)
    )
);

CREATE UNIQUE INDEX item_loans_open_uq
  ON item_loans (item_id)
  WHERE returned_at IS NULL;

CREATE INDEX item_loans_order_idx
  ON item_loans (order_id);

-- ---------- Notifikasi ----------
CREATE TABLE app_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  body TEXT NOT NULL,
  type VARCHAR(50) NOT NULL DEFAULT 'info',
  order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX app_notifications_user_idx
  ON app_notifications (user_id, read_at);

